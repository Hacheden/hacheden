      <ul class="story-list">${STORIES.map(s => `<li><button type="button" data-sopen="${s.id}"><b>${s.title}</b><span class="${PROG.stories.includes(s.id) ? "read" : ""}">${s.sub}</span></button></li>`).join("")}</ul>
